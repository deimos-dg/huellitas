test('Idle respira y parpadea con autonomía apagada, incluido después de caminar', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto(practiceUrl)
  await autonomyControl(page).uncheck()
  const stage = page.getByTestId('room-stage')
  const pet = page.getByTestId('room-pet')
  const artwork = page.locator('.room-pet-artwork')
  const breath = artwork.locator('.room-pet-breath > span')
  await expect(page.locator('.room-pet-drawing')).toHaveAttribute('data-frame', '12')
  await stage.evaluate(node => {
    const observer = new MutationObserver(() => {
      const lids = Array.from(node.querySelectorAll<HTMLElement>('.room-pet-eyelid'))
      if (lids.length === 2 && lids[0].style.backgroundPosition !== lids[1].style.backgroundPosition) {
        node.setAttribute('data-observed-blink', 'yes')
      }
    })
    observer.observe(node, { childList: true, subtree: true })
  })
  const initialBreath = await breath.evaluate(node => getComputedStyle(node).translate)
  await expect.poll(() => breath.evaluate(node => getComputedStyle(node).translate)).not.toBe(initialBreath)
  await expect(artwork).toHaveCSS('scale', 'none')
  await expect(stage).toHaveAttribute('data-observed-blink', 'yes', { timeout: 7000 })
  await expect(stage).toHaveAttribute('data-state', 'Idle')
  await expectPose(pet, 574, 590, 0)

  await chooseFloor(page, 790, 625)
  await expect(stage).toHaveAttribute('data-state', 'Walking')
  await expect(stage).toHaveAttribute('data-state', 'Idle')
  await expect(page.locator('.room-pet-drawing')).toHaveAttribute('data-frame', '12')
  const arrivalBreath = await breath.evaluate(node => getComputedStyle(node).translate)
  await expect.poll(() => breath.evaluate(node => getComputedStyle(node).translate)).not.toBe(arrivalBreath)
  await expectPose(pet, 790, 625)
})

test('la autonomía empieza activa, cede ante un destino y se reanuda tras reposo', async ({ page }) => {
  await page.addInitScript(() => { Math.random = () => .4 })
  await page.goto(practiceUrl)
  const autonomy = autonomyControl(page)
  const stage = page.getByTestId('room-stage')
  await expect(autonomy).toBeChecked()
  await expect(stage).toHaveAttribute('data-state', 'Looking', { timeout: 13_000 })
  await chooseFloor(page, 900, 610)
  await expect(stage).toHaveAttribute('data-state', 'Walking')
  await expect(stage).toHaveAttribute('data-state', 'Idle')
  const pet = page.getByTestId('room-pet')
  await expectPose(pet, 900, 610)
  const restedAt = Date.now()
  await expect(stage).toHaveAttribute('data-state', 'Looking', { timeout: 13_000 })
  expect(Date.now() - restedAt).toBeGreaterThan(6000)
  await expectPose(pet, 900, 610)
  await autonomy.uncheck()
  await expect(stage).toHaveAttribute('data-state', 'Idle')
  await page.reload()
  await expect(autonomy).not.toBeChecked()
  await expectPose(pet, 900, 610)
})
