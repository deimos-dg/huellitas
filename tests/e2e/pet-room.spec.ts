import { expect, test } from '@playwright/test'
import type { Locator, Page } from '@playwright/test'

const storageKey = 'huellitas.petmotion2d.v1'
const practiceUrl = '/habitacion?escena=golden-room'
const autonomyControl = (page: Page) => page.getByRole('checkbox', { name: 'Comportamiento autónomo' })

async function chooseFloor(page: Page, x: number, y: number) {
  const stage = page.getByTestId('room-stage')
  const floor = stage.getByRole('button', { name: 'Desplazar al Golden por el suelo' })
  const [stageBox, floorBox] = await Promise.all([stage.boundingBox(), floor.boundingBox()])
  if (!stageBox || !floorBox) throw new Error('Room stage is missing')
  await floor.click({ position: { x: x / 1280 * stageBox.width, y: y / 720 * stageBox.height + stageBox.y - floorBox.y } })
}

async function expectPose(pet: Locator, x: number, y: number, tolerance = 2) {
  const position = await pet.evaluate(node => ({ x: Number(node.getAttribute('data-x')), y: Number(node.getAttribute('data-y')) }))
  expect(Math.abs(position.x - x)).toBeLessThanOrEqual(tolerance)
  expect(Math.abs(position.y - y)).toBeLessThanOrEqual(tolerance)
}

test('abre la habitación desde el jardín, respeta el suelo y conserva el acceso al creador', async ({ page }) => {
  await page.goto('/#jardin')
  await page.getByRole('link', { name: 'Visita la habitación' }).click()
  await expect(page).toHaveURL(/\/habitacion$/)
  await page.getByLabel('Escenario').selectOption('golden-room')
  await expect(page).toHaveURL(/escena=golden-room$/)
  await expect(page.getByRole('heading', { name: 'Habitación del Golden' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Golden Retriever', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Sentarse' })).toBeInViewport({ ratio: 1 })
  await autonomyControl(page).uncheck()

  const stage = page.getByTestId('room-stage')
  const pet = page.getByTestId('room-pet')
  await expectPose(pet, 574, 590)
  await chooseFloor(page, 25, 645)
  await expect(page.getByRole('status')).toContainText('Elige un punto libre del suelo')
  await expectPose(pet, 574, 590)

  await chooseFloor(page, 80, 521)
  await expect(stage).toHaveAttribute('data-state', 'Walking')
  await expect(stage).toHaveAttribute('data-state', 'Idle', { timeout: 8000 })
  await expectPose(pet, 80, 521)
  await expect(pet).toHaveAttribute('data-facing', 'left')

  await page.getByRole('link', { name: 'Creador', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Crea tu mascota' })).toBeVisible()
})

test('acciona los tres objetos de la escena, guarda el descanso y puede levantarse tras recargar', async ({ page }) => {
  await page.goto(practiceUrl)
  await autonomyControl(page).uncheck()
  const stage = page.getByTestId('room-stage')
  const pet = page.getByTestId('room-pet')
  await stage.getByRole('button', { name: 'Comedero' }).click()
  await expect(stage).toHaveAttribute('data-state', 'Eating', { timeout: 8000 })
  await expectPose(pet, 926, 507, 0)
  await expect(stage.locator('.room-object-food')).toBeHidden()
  await expect(stage).toHaveAttribute('data-state', 'Sitting')

  await stage.getByRole('button', { name: 'Bebedero' }).click()
  await expect(stage).toHaveAttribute('data-state', 'Drinking', { timeout: 8000 })
  await expectPose(pet, 1083, 507, 0)
  await expect(stage).toHaveAttribute('data-state', 'Sitting')

  await stage.getByRole('button', { name: 'Cama' }).click()
  await expect(stage).toHaveAttribute('data-state', 'Resting', { timeout: 9000 })
  await expectPose(pet, 385, 536, 0)
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{}').posture, storageKey)).toBe('resting')
  await page.reload()
  await expect(stage).toHaveAttribute('data-state', 'Resting')
  await expectPose(pet, 385, 536, 0)
  await page.getByRole('button', { name: 'Levantarse' }).click()
  await expect(stage).toHaveAttribute('data-state', 'Idle', { timeout: 5000 })
})

test('sigue operativa si falta el atlas y recupera el último estado estable', async ({ page }) => {
  await page.route(/golden(?:-room)?-art[^/]*\.webp(?:\?|$)/, route => (
    route.request().resourceType() === 'image' ? route.abort() : route.continue()
  ))
  await page.goto(practiceUrl)
  await autonomyControl(page).uncheck()
  await expect(page.getByRole('img', { name: /representación provisional/ })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('Recurso de animación no disponible')
  const stage = page.getByTestId('room-stage')
  await stage.getByRole('button', { name: 'Comedero' }).click()
  await expect(stage).toHaveAttribute('data-state', 'Eating', { timeout: 8000 })
  await expect(page.getByRole('status')).toContainText('Recurso de animación no disponible')
  await expect(stage.locator('.room-object-food')).toBeVisible()
  await expect(stage).toHaveAttribute('data-state', 'Sitting')
  await page.reload()
  await expect(stage).toHaveAttribute('data-state', 'Sitting')
  await expectPose(page.getByTestId('room-pet'), 926, 507, 0)
  await page.getByRole('button', { name: 'Levantarse' }).click()
  await expect(stage).toHaveAttribute('data-state', 'Idle')
})

